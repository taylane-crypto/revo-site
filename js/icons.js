  var SVG_NS = "http://www.w3.org/2000/svg";

  function build(name, from) {
    var inner = ICONS[name];
    if (!inner) return null;
    var svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("xmlns", SVG_NS);
    svg.setAttribute("viewBox", "0 0 24 24");
    svg.setAttribute("fill", "none");
    svg.setAttribute("stroke", "currentColor");
    svg.setAttribute("stroke-width", "1.6");
    svg.setAttribute("stroke-linecap", "round");
    svg.setAttribute("stroke-linejoin", "round");
    svg.setAttribute("aria-hidden", "true");
    svg.setAttribute("focusable", "false");
    var cls = (from.getAttribute("class") || "").split(/\s+/).filter(Boolean);
    if (cls.indexOf("rv-icon") === -1) cls.unshift("rv-icon");
    cls.push("lucide", "lucide-" + name);
    svg.setAttribute("class", cls.join(" "));
    svg.innerHTML = inner;
    return svg;
  }

  function createIcons() {
    var nodes = document.querySelectorAll("i[data-lucide]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var svg = build(el.getAttribute("data-lucide"), el);
      if (svg) el.replaceWith(svg);
      else el.removeAttribute("data-lucide"); /* ícone desconhecido: some em silêncio, sem erro */
    }
  }

